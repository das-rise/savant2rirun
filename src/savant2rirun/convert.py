import argparse
import json
import os
import sys
from datetime import datetime, timezone
from math import pi
from typing import Tuple

from rich_argparse import RichHelpFormatter


def timestamp_now_dataprov() -> str:
    """Returns the current timestamp in ISO 8601 format for use with dataprov."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


class OpenLabelParser:
    """
    Parses an OpenLabel file generated by SAVANT (https://github.com/RI-SE/SAVANT/tree/main) to extract vehicle trajectories.
    """

    def __init__(self, filepath: str):
        """
        Initializes the parser with the path to the OpenLabel file.

        Args:
            filepath (str): Path to the OpenLabel .json file.
        """
        self.filepath = filepath
        self.vehicles = dict()
        self._written_trajectories = set()
        with open(self.filepath, "r") as file:
            self.data = json.load(file)

    def _get_vehicle_type(self, id: int) -> str:
        """Gets the vehicle type for a given object ID."""
        return self.data["openlabel"]["objects"][str(id)]["type"]

    def _get_frame(self, frame: int) -> dict:
        """Gets the data for a given frame number."""
        return self.data["openlabel"]["frames"][str(frame)]

    def _get_time(self, frame_id: int, framerate: float) -> float:
        """Gets the timestamp for a given frame ID based on the framerate."""
        return frame_id / framerate

    def _parse_bounding_box(
        self, frame_data: dict, object_id: int
    ) -> Tuple[float, float, float]:
        """
        Parses a bounding box from the OpenLabel data for a given frame and object ID.

        Returns:
            A tuple containing the x and y coordinates of the bounding box center in pixels,
            and the angle of the bounding box in degrees.
        """
        object_data = frame_data["objects"][str(object_id)]["object_data"]
        bb = object_data["rbbox"][0]["val"]
        pixel_x, pixel_y, _, _, angle = bb
        angle = (
            angle * 180 / pi + 180
        )  # Convert angle from radians to degrees and correct for coordinate system
        return pixel_x, pixel_y, angle

    def _iter_frames(self, start_frame: int = None, end_frame: int = None):
        """Iterates over all frames in the OpenLabel data."""
        frames = self.data["openlabel"]["frames"]
        for frame_id in sorted(frames.keys(), key=int):
            if (start_frame is not None and int(frame_id) < start_frame) or (
                end_frame is not None and int(frame_id) > end_frame
            ):
                continue
            yield frame_id, frames[frame_id]

    def _iter_vehicles_in_frame(self, frame_data: dict):
        """
        Iterates over all vehicles in a given frame.

        Yields:
            A tuple containing the object ID, bounding box data, and vehicle type.
        """
        for object_id in frame_data["objects"].keys():
            yield (
                object_id,
                self._parse_bounding_box(frame_data, object_id),
                self._get_vehicle_type(object_id),
            )

    def parse(
        self, framerate: float, start_frame: int = None, end_frame: int = None
    ) -> None:
        """
        Parses the OpenLabel file, optionally between the given frames,
        and populates the vehicles dictionary.

        Args:
            start_frame (int, optional): The starting frame number to parse. Defaults to None.
            end_frame (int, optional): The ending frame number to parse. Defaults to None.
        """
        for frame_id, frame_data in self._iter_frames(start_frame, end_frame):
            for id, bbox, vehicle_type in self._iter_vehicles_in_frame(frame_data):
                x, y, angle = bbox
                timestamp = self._get_time(int(frame_id), framerate)
                trajectory_point = (x, y, timestamp, angle)
                if id not in self.vehicles:
                    self.vehicles[id] = {
                        "type": vehicle_type,
                        "trajectory": [trajectory_point],
                        "frames": [frame_id],
                    }
                else:
                    self.vehicles[id]["trajectory"].append(trajectory_point)
                    self.vehicles[id]["frames"].append(frame_id)

    def write_trajectories(self, outpath: str):
        """
        Writes the trajectory of each vehicle to a CSV file.

        Args:
            outpath (str): Directory where the generated trajectory files will be saved.
        """
        if not os.path.exists(outpath):
            os.makedirs(outpath)

        for vehicle_id, vehicle in self.vehicles.items():
            vehicle_type = vehicle["type"]
            trajectory = vehicle["trajectory"]
            filename = f"vehicle_{vehicle_id}_{vehicle_type}.csv"
            output_path = os.path.join(outpath, filename)

            with open(output_path, "w", newline="") as csvfile:
                print("x_loc [m],y_loc [m],Time [s],Heading [deg]", file=csvfile)
                for point in trajectory:
                    print(*point, sep=",", file=csvfile)

            self._written_trajectories.add(filename)

    def convert_pixel_to_geo(
        self, georef_file: str, proj_string: str, offset: Tuple[float, float] = (0, 0)
    ):
        """
        Converts the pixel coordinates of the trajectories to geographic coordinates.

        Args:
            georef_file(str): Path to the georeference file (*.json) generated by orbit-georef (see https://github.com/RI-SE/ORBIT/tree/main/orbit-georef)
            proj_string (str): The projection string for the source coordinate system.
            offset (Tuple[float, float], optional): An optional (x, y) offset to apply to the coordinates after conversion. Defaults to (0, 0).
        """
        from orbit_georef import load_georef

        georef = load_georef(georef_file)

        for vehicle in self.vehicles.values():
            x_y_trajectory = [point[:2] for point in vehicle["trajectory"]]
            converted_trajectory = georef.pixels_to_geo_batch(
                x_y_trajectory, proj_string
            )
            for i, (x_conv, y_conv) in enumerate(converted_trajectory):
                vehicle["trajectory"][i] = (
                    x_conv - offset[0],
                    y_conv - offset[1],
                ) + vehicle["trajectory"][i][2:]

    def get_written_trajectories(self):
        """Returns the set of trajectory filenames that have been written."""
        return self._written_trajectories


def main():

    parser = argparse.ArgumentParser(
        prog="Savant2RIRUN",
        description="Convert trajectories contained in OpenLabel files from Savant for use with RIRUN.",
        formatter_class=RichHelpFormatter,
    )

    parser.add_argument(
        "openlabel_file",
        type=str,
        help="The filepath to the OpenLabel file to process.",
    )

    parser.add_argument(
        "georef_file",
        type=str,
        default=None,
        help="The path to the georeference file (*.json) generated by orbit-georef",
    )

    parser.add_argument(
        "outpath",
        type=str,
        help="The directory where the generated trajectory files will be saved.",
    )

    parser.add_argument(
        "--start_frame",
        type=int,
        default=None,
        help="The starting frame number to parse. Defaults to None (start from the beginning).",
    )

    parser.add_argument(
        "--end_frame",
        type=int,
        default=None,
        help="The ending frame number to parse. Defaults to None (parse until the end).",
    )

    parser.add_argument(
        "--proj",
        type=str,
        default=None,
        help="The projection string to use for converting pixel coordinates to geographic coordinates. If omitted, defaults to a WGS84 projection.",
    )

    parser.add_argument(
        "--offset",
        type=float,
        nargs=2,
        metavar=("X", "Y"),
        default=(0, 0),
        help="An optional (x, y) offset to apply to the coordinates after conversion. Defaults to (0, 0).",
    )

    parser.add_argument(
        "--framerate",
        type=float,
        default=30,
        help="The framerate of the video in frames per second. Defaults to 30.",
    )

    parser.add_argument(
        "--use-dataprov",
        action="store_true",
        help="Use dataprov library to create a provenance chain for the conversion",
    )

    parser.add_argument(
        "--dataprov-input-provenance-files",
        type=str,
        nargs="*",
        default=[],
        help="List of dataprov provenance files in the order 'OpenLabel, georef' to include as inputs in the provenance chain. One or both can be 'None'. Only used if --use-dataprov is set.",
    )

    args = parser.parse_args()

    start_time = timestamp_now_dataprov()

    openlabel_parser = OpenLabelParser(args.openlabel_file)
    openlabel_parser.parse(args.framerate, args.start_frame, args.end_frame)
    openlabel_parser.convert_pixel_to_geo(args.georef_file, args.proj, args.offset)

    openlabel_parser.write_trajectories(args.outpath)

    if args.use_dataprov:
        from dataprov import ProvenanceChain
        from importlib.metadata import metadata
        import hashlib
        import time

        unique_hash = hashlib.sha256(
            (str(vars(args)) + str(time.time_ns())).encode()
        ).hexdigest()
        tool_name = "savant2rirun"
        meta = metadata(tool_name)
        entity_id = "Savant2RIRUN_conversion_" + unique_hash[:8]

        if args.dataprov_input_provenance_files:
            input_provenance_files = args.dataprov_input_provenance_files
        else:
            input_provenance_files = None

        chain = ProvenanceChain.create(
            entity_id=entity_id,
            initial_source=args.openlabel_file,
            description="Conversion of OpenLabel trajectories from SAVANT to RIRUN format. "
            "The former is a JSON file, the latter a set of CSV files, one per vehicle, "
            "containing the trajectory points with geographic coordinates.",
            tags=[
                "Savant2RIRUN",
                "conversion",
                "OpenLabel",
                "RIRUN",
                "trajectory",
                "Synergies",
            ],
        )

        chain.add(
            started_at=start_time,
            ended_at=timestamp_now_dataprov(),
            tool_name=tool_name,
            tool_version=meta["Version"],
            arguments=" ".join(sys.argv[1:]),
            operation="Extract all individual trajectories from the OpenLabel file, one per vehicle, and convert their coordinates from pixel to geographic coordinates using the provided georeference file and projection string.",
            inputs=[args.openlabel_file, args.georef_file],
            input_formats=["OpenLabel/JSON", "orbit-georef/JSON"],
            outputs=list(openlabel_parser.get_written_trajectories()),
            output_formats=["CSV"] * len(openlabel_parser.get_written_trajectories()),
            input_provenance_files=input_provenance_files,
            capture_environment=True
        )

        chain.save(f"{args.outpath}/{entity_id}_prov.json")


if __name__ == "__main__":
    main()
